const byId = id => document.getElementById(id);
const escapeHTML = value => String(value ?? "").replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
const whatsappURL = (message, phone = WHATSAPP_NUMBER) =>
  `https://wa.me/${String(phone).replace(/\D/g, "")}?text=${encodeURIComponent(message)}`;

const collectionsGrid = byId("collectionsGrid");
const productsGrid = byId("productsGrid");
const collectionTitle = byId("collectionTitle");
const collectionDescription = byId("collectionDescription");
const modal = byId("modal");
const modalImage = byId("modalImage");
const modalTitle = byId("modalTitle");
const modalDesc = byId("modalDesc");
const modalLink = byId("modalLink");
let currentCollection = null;
let lastFocusedElement = null;

function collectionURL(id) {
  return `collection.html?id=${encodeURIComponent(id)}`;
}

function renderCollections() {
  if (!collectionsGrid) return;
  collectionsGrid.innerHTML = collections.map(c => `
    <article class="collection" aria-label="${escapeHTML(c.name)} collection">
      <div class="collection-image">
        <img loading="lazy" src="${escapeHTML(c.cover)}" alt="${escapeHTML(c.name)}"
          onerror="this.onerror=null;this.alt='Product image unavailable';">
      </div>
      <div class="collection-info">
        <h3>${escapeHTML(c.name)}</h3>
        <p>${c.count} designs in this collection</p>
        <a class="collection-link" href="${collectionURL(c.id)}">Open collection ↗</a>
      </div>
    </article>`).join("");
}

function renderProducts(collection) {
  if (!productsGrid || !collection) return;
  currentCollection = collection;
  collectionTitle.textContent = collection.name;
  collectionDescription.textContent = collection.description;
  document.title = `${collection.name} | Rishabh Jewellers`;

  productsGrid.innerHTML = collection.products.map((p, i) => {
    const message = `Hello Rishabh Jewellers, please share price, net weight, purity and availability for ${p.name} (${p.ref}) from ${collection.name}.`;
    return `<article class="product-card">
      <div class="product-image-wrap" role="button" tabindex="0"
           aria-label="View ${escapeHTML(p.name)} larger" data-product-index="${i}">
        <img class="product-image" loading="lazy" src="${escapeHTML(p.image)}"
             alt="${escapeHTML(p.name)}"
             onerror="this.onerror=null;this.alt='Image unavailable';">
        <span class="product-tag">${escapeHTML(collection.name)}</span>
      </div>
      <div class="product-info">
        <p class="product-reference">Design reference ${escapeHTML(p.ref)}</p>
        <h3 class="product-name">${escapeHTML(p.name)}</h3>
        <p class="product-weight">Net weight: please enquire</p>
        <p class="product-note">${escapeHTML(p.note)}</p>
        <a class="product-wa" href="${whatsappURL(message)}" target="_blank" rel="noopener noreferrer">Enquire on WhatsApp ↗</a>
        <a class="alternate-wa" href="${whatsappURL(message, ALTERNATE_WHATSAPP_NUMBER)}" target="_blank" rel="noopener noreferrer">WhatsApp alternate number ↗</a>
      </div>
    </article>`;
  }).join("");
}

function openProduct(index) {
  if (!currentCollection || !modal) return;
  const p = currentCollection.products[index];
  if (!p) return;
  lastFocusedElement = document.activeElement;
  modalImage.src = p.image;
  modalImage.alt = p.name;
  modalTitle.textContent = p.name;
  modalDesc.textContent = `${currentCollection.name} · Design reference ${p.ref} · Please enquire for net weight.`;
  const message = `Hello Rishabh Jewellers, please share price, net weight, purity and availability for ${p.name} (${p.ref}) from ${currentCollection.name}.`;
  modalLink.href = whatsappURL(message);
  modal.classList.add("open");
  modal.setAttribute("aria-hidden", "false");
  document.body.style.overflow = "hidden";
  byId("close")?.focus();
}

function closeProductModal() {
  if (!modal) return;
  modal.classList.remove("open");
  modal.setAttribute("aria-hidden", "true");
  document.body.style.overflow = "";
  lastFocusedElement?.focus?.();
}

function initHome() {
  renderCollections();
  byId("hamb")?.addEventListener("click", () => byId("nav")?.classList.toggle("open"));
  byId("nav")?.querySelectorAll("a").forEach(a =>
    a.addEventListener("click", () => byId("nav")?.classList.remove("open"))
  );
}

function initCollectionPage() {
  const params = new URLSearchParams(window.location.search);
  const id = params.get("id");
  const collection = collections.find(c => c.id === id) || collections[0];
  renderProducts(collection);

  byId("backToCollections")?.addEventListener("click", e => {
    e.preventDefault();
    window.location.href = "index.html#collections";
  });

  productsGrid?.addEventListener("click", e => {
    const wrap = e.target.closest("[data-product-index]");
    if (wrap) openProduct(Number(wrap.dataset.productIndex));
  });

  productsGrid?.addEventListener("keydown", e => {
    const wrap = e.target.closest("[data-product-index]");
    if (wrap && (e.key === "Enter" || e.key === " ")) {
      e.preventDefault();
      openProduct(Number(wrap.dataset.productIndex));
    }
  });
}

byId("close")?.addEventListener("click", closeProductModal);
modal?.addEventListener("click", e => { if (e.target === modal) closeProductModal(); });
document.addEventListener("keydown", e => { if (e.key === "Escape") closeProductModal(); });
if (byId("year")) byId("year").textContent = new Date().getFullYear();

if (collectionsGrid) initHome();
if (productsGrid) initCollectionPage();
